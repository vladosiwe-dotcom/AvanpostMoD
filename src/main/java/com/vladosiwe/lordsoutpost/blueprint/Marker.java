package com.vladosiwe.lordsoutpost.blueprint;

/** Функциональные точки чертежа: по ним жители находят рабочие места, посты и склады. */
public enum Marker {
    /** Центр внешних ворот (уровень земли). */
    GATE,
    /** Вход в цитадель (донжон). */
    KEEP_DOOR,
    /** Место Капитана (до захвата) и Управляющего (после). */
    THRONE,
    /** Сундук Капитана с редкой добычей. */
    TREASURE,
    /** Сундук Дани: сюда поселение складывает доход Лорда. */
    TRIBUTE,
    /** Бочка снабжения: предметы из неё уходят на склад поселения. */
    SUPPLY,
    /** Доска заданий. */
    BOARD,
    /** Перед дверью склада: сюда рабочие подходят с добычей. */
    STORAGE,
    /** Внутри склада у бочек: отсюда рабочие раскладывают добычу. */
    STORE_INSIDE,
    /** Бочки склада: в них лежат запасы поселения. */
    STOCKPILE,
    /** Посты стражи у двери склада. */
    STORE_GUARD,
    /** Дно шахтного ствола: отсюда шахтёр ведёт штрек. */
    MINE_SHAFT,
    /** Клетка штрека сразу за стволом: задаёт направление проходки. */
    MINE_DIR,
    SMITHY,
    MINE,
    WOODYARD,
    /** Центр загона. */
    PEN,
    /** Центр поля фермера; вода находится в блоке под маркером. */
    FARM,
    /** Койки лазарета. */
    INFIRMARY,
    /** Рабочее место Придворного Мага. */
    MAGE,
    /** Спальные места. */
    HOUSING,
    /** Посты стражи на стенах, башнях и у ворот. */
    GUARD_POST,
    /** Точки внутреннего обхода по умолчанию. */
    PATROL,
    /** Точки внешнего обхода по умолчанию (за стенами). */
    OUTER_PATROL,
    /** Свободное место во дворе (сбор, штандарт). */
    YARD,
    /** Место сбора каравана за воротами. */
    CARAVAN,
    /** Обычные сундуки с добычей (для диких аванпостов). */
    LOOT_CHEST,
    /** Личные сундуки Лорда: открывает только сам Лорд. */
    LORD_CHEST,
    /** Рамка портала на верхнем этаже донжона (тир 3): сюда ведёт Зеркало Лорда. */
    PORTAL_FRAME
}
