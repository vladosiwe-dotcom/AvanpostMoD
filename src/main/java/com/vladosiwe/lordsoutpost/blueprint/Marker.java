package com.vladosiwe.lordsoutpost.blueprint;

/** Функциональные точки чертежа: по ним жители находят рабочие места, посты и склады. */
public enum Marker {
    /** Центр внешних ворот (уровень земли). */
    GATE,
    /** Вход в цитадель (донжон). */
    KEEP_DOOR,
    /** Место Капитана (до захвата) и Управляющего (после). */
    THRONE,
    /** Сундук Капитана с редкой добычей. */
    TREASURE,
    /** Сундук Дани: сюда поселение складывает доход Лорда. */
    TRIBUTE,
    /** Бочка снабжения: предметы из неё уходят на склад поселения. */
    SUPPLY,
    /** Доска заданий. */
    BOARD,
    /** Куда рабочие несут добычу. */
    STORAGE,
    SMITHY,
    MINE,
    WOODYARD,
    /** Центр загона. */
    PEN,
    /** Койки лазарета. */
    INFIRMARY,
    /** Рабочее место Придворного Мага. */
    MAGE,
    /** Спальные места. */
    HOUSING,
    /** Посты стражи на стенах, башнях и у ворот. */
    GUARD_POST,
    /** Точки внутреннего обхода по умолчанию. */
    PATROL,
    /** Точки внешнего обхода по умолчанию (за стенами). */
    OUTER_PATROL,
    /** Свободное место во дворе (сбор, штандарт). */
    YARD,
    /** Место сбора каравана за воротами. */
    CARAVAN,
    /** Обычные сундуки с добычей (для диких аванпостов). */
    LOOT_CHEST
}
